#!/usr/bin/env python3
"""
report.py: tables and the verdict on every registered prediction, from the JSON analyse.py wrote.

    python3 experiments/specificity/report.py            # reads results/, writes results/REPORT.md
    python3 experiments/specificity/report.py --dir experiments/specificity/results/dryrun

Every number in REPORT.md is read from results/specificity_<series>.json. Nothing is typed in.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SERIES = ("GSE106474", "GSE112294", "GSE113074")
NAMES = {"detected_genes": "gene count", "pcc_x_degree": "PCC(x, degree)", "shannon_entropy": "Shannon entropy",
         "log10_library_size": "log library size", "joint": "all four", "stemfinder_cell_cycle_score": "cell-cycle score"}
AUDITED = ("CytoTRACE", "SR", "ORIGINS", "NCG", "dpath", "StemFinder", "SLICE", "CCAT", "MCE")
CLEARING = ("CytoTRACE", "SR", "ORIGINS", "NCG", "dpath", "StemFinder")


def f(x, d=3):
    return "n/a" if x is None else f"{x:+.{d}f}"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


def holm(ps):
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, running = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = running
    return adj


def build(d):
    L, pred = [], {}
    z = d["GSE106474"]

    L += ["# Specificity, the replicated unit and depth: results", "",
          "Generated by `report.py` from `specificity_<series>.json`. Plan: `PREREG.md`.", ""]

    # ---- A. the floor
    L += ["## A. How often an arbitrary gene set clears the floor", "",
          "Share of the 1,000 random 200-gene sets (A1) whose conditional skill is above the registered floor of Eq. (4) "
          "on GSE106474. Bracketed: the larger of the floors at the two grid correlations that bracket the control's own, "
          "the reading the plan registers. Nearest: the audit's lookup. Not distant: nearest, controls within 0.15 of a grid point only.", "",
          "| covariates removed | bracketed | nearest | nearest, not distant | distant controls | median CS | 2.5th | 97.5th | "
          "median abs. Spearman with covariates |", "|---|---|---|---|---|---|---|---|---|"]
    s1 = []
    for c in ("detected_genes", "pcc_x_degree", "shannon_entropy", "log10_library_size", "joint"):
        e = z["controls"]["a1_g200"][c]
        q = e["conditional_skill"]["quantiles"]
        s1.append(e.get("fraction_above_registered_floor_bracketed"))
        L.append(f"| {NAMES[c]} | {pct(e.get('fraction_above_registered_floor_bracketed'))} | {pct(e.get('fraction_above_registered_floor_nearest'))} | "
                 f"{pct(e.get('fraction_above_registered_floor_nearest_not_distant'))} | {e.get('controls_distant_from_grid')} | {f(q['0.5'])} | "
                 f"{f(q['0.025'])} | {f(q['0.975'])} | {e['max_abs_spearman_with_covariates']['quantiles']['0.5']:.2f} |")
    pred["S1"] = (all(v is not None and v > 0.5 for v in s1), "share above the bracketed registered floor: " + ", ".join(pct(v) for v in s1))
    L += ["", "Against the permutation floor (first controls of A1, 200 draws):", "",
          "| series | controls | gene count | PCC(x, degree) | Shannon entropy | log library size |", "|---|---|---|---|---|---|"]
    for g in SERIES:
        if g in d:
            p = d[g]["controls_permutation_floor"]
            L.append(f"| {g} | {p['controls']} | " + " | ".join(pct(p["by_primitive"][c]["fraction_above"]) for c in
                                                                 ("detected_genes", "pcc_x_degree", "shannon_entropy", "log10_library_size")) + " |")
    L += ["", "Other control families on GSE106474, conditional skill on each covariate set (median; 97.5th percentile):", "",
          "| family | gene count | PCC(x, degree) | Shannon entropy | log library size | all four |", "|---|---|---|---|---|---|"]
    for fam, label in (("a1_g20", "A1, 20 genes"), ("a1_g200", "A1, 200 genes"), ("a1_g2000", "A1, 2,000 genes"), ("a2", "A2, permuted degree")):
        cells = []
        for c in ("detected_genes", "pcc_x_degree", "shannon_entropy", "log10_library_size", "joint"):
            q = z["controls"][fam][c]["conditional_skill"]["quantiles"]
            cells.append(f"{f(q['0.5'])}; {f(q['0.975'])}")
        L.append(f"| {label} | " + " | ".join(cells) + " |")

    # ---- A. rows against controls
    L += ["", "## A. Each audited row against arbitrary gene sets", "",
          "CS: registered conditional skill on the declared primitive, the row's increment over it. A1 97.5th: the 97.5th "
          "percentile of the increments of 1,000 random 200-gene sets over the same primitive on the same cells. Percentile: share "
          "of those controls below the row. rho: absolute Spearman correlation with the primitive, the row's and the controls' median.", "",
          "| series | row | primitive | rho, row / controls | CS | A1 97.5th | percentile | exceeds | joint CS | joint A1 97.5th | exceeds | "
          "controls with larger marginal tau | exceeds A1 at 20 / 2,000 genes | exceeds A2 |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    exceed = {}
    for g in SERIES:
        if g not in d:
            continue
        for name, r in d[g]["rows"].items():
            v = r["vs_controls"]
            a = v["a1_g200"]
            exceed[(g, name)] = a["exceeds_p975"]
            sens = "/".join("yes" if v[k]["exceeds_p975"] else "no" for k in ("a1_g20", "a1_g2000") if k in v) or "n/a"
            L.append(f"| {g} | {name} | {NAMES[r['primitive']]} | {abs(r['spearman_with_primitive']):.2f} / "
                     f"{a['control_median_abs_spearman_with_primitive']:.2f} | {f(r['conditional_skill'])} | {f(a['control_p975'])} | "
                     f"{pct(a['percentile'])} | {'yes' if a['exceeds_p975'] else 'no'} | {f(r['conditional_skill_joint'])} | "
                     f"{f(a['joint_control_p975'])} | {'yes' if a['joint_exceeds_p975'] else 'no'} | "
                     f"{pct(a['fraction_of_controls_with_larger_abs_marginal_tau'])} | {sens} | "
                     f"{'yes' if v['a2']['exceeds_p975'] else 'no'} |")
    n_exceed = sum(exceed[("GSE106474", n)] for n in CLEARING)
    n_joint = sum(d["GSE106474"]["rows"][n]["vs_controls"]["a1_g200"]["joint_exceeds_p975"] for n in CLEARING)
    L += ["", f"Of the six rows that clear the registered floor on GSE106474, {n_joint} have a joint increment above the controls' 97.5th percentile.",
          f"Of the same six, {n_exceed} have an increment over the declared primitive above the controls' 97.5th percentile: "
          + (", ".join(n for n in CLEARING if exceed[("GSE106474", n)]) or "none") + "."]
    pred["S2"] = (exceed[("GSE106474", "CytoTRACE")] and exceed.get(("GSE112294", "CytoTRACE"), False)
                  and not exceed.get(("GSE113074", "CytoTRACE"), True),
                  "CytoTRACE exceeds A1 on " + ", ".join(g for g in SERIES if exceed.get((g, "CytoTRACE"))))
    pred["S4"] = (not exceed[("GSE106474", "dpath")] and not exceed[("GSE106474", "StemFinder")],
                  f"dpath {'exceeds' if exceed[('GSE106474', 'dpath')] else 'does not exceed'}, "
                  f"StemFinder {'exceeds' if exceed[('GSE106474', 'StemFinder')] else 'does not exceed'}")
    pred["S5"] = (not any(exceed[("GSE106474", n)] for n in ("SR", "ORIGINS", "NCG")),
                  "exceed: " + (", ".join(n for n in ("SR", "ORIGINS", "NCG") if exceed[("GSE106474", n)]) or "none"))

    # ---- A3
    L += ["", "## A. CytoTRACE against its own pipeline", "",
          "Conditional skill on gene count. Random: 100 random 200-gene sets in place of the gene-count signature.", "",
          "| series | genes | smoothing | value or median | 2.5th | 97.5th | CytoTRACE row exceeds 97.5th |", "|---|---|---|---|---|---|---|"]
    s3 = []
    for g in ("GSE106474", "GSE112294"):
        if g not in d or "cytotrace_ablation" not in d[g]:
            continue
        ab, rows = d[g]["cytotrace_ablation"], d[g]["rows"]
        for key, row, sm in (("a3_unsmoothed", "GCS", "off"), ("a3", "CytoTRACE", "on")):
            q = ab[key]["detected_genes"]["quantiles"]
            ex = rows[row]["vs_controls"][key]["exceeds_p975"]
            L.append(f"| {g} | chosen by gene count | {sm} | {f(rows[row]['conditional_skill'])} | | | {'yes' if ex else 'no'} |")
            L.append(f"| {g} | random | {sm} | {f(q['0.5'])} | {f(q['0.025'])} | {f(q['0.975'])} | |")
            if key == "a3":
                s3.append(ex)
        L.append(f"| {g} | joint residual, smoothing on: CytoTRACE {f(rows['CytoTRACE']['conditional_skill_joint'])}, random median "
                 f"{f(ab['a3']['joint']['quantiles']['0.5'])}, 97.5th {f(ab['a3']['joint']['quantiles']['0.975'])} | | | | | "
                 f"{'yes' if rows['CytoTRACE']['vs_controls']['a3']['joint_exceeds_p975'] else 'no'} |")
    if len(s3) == 2:
        pred["S3"] = (not any(s3), f"CytoTRACE exceeds A3 on {sum(s3)} of 2 zebrafish series")

    # ---- B
    L += ["", "## B. The trend over samples", "",
          "Kendall's tau between the per-sample mean of the stratum-mean residual and the sample's stage, stage labels permuted between "
          "samples inside a sequencing batch (one group on GSE112294). Holm over the audited rows of the series. Least squares: the same "
          "test on the residual of Eq. (2), which the calibration shows to be anti-conservative. Joint: a cross-fitted boosted residual on the four primitives.", "",
          "| series | row | samples | tau | p | Holm p | sign agrees with CS | supported | no batch strata p | least-squares p | joint p |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    supported = {}
    for g in ("GSE106474", "GSE112294"):
        if g not in d:
            continue
        rows = {n: r for n, r in d[g]["rows"].items() if "sample_test" in r and n != "GCS"}
        adj = dict(zip(rows, holm([r["sample_test"]["p_two_sided"] for r in rows.values()])))
        for n, r in rows.items():
            t = r["sample_test"]
            agree = (t["S"] > 0) == (r["conditional_skill"] > 0) and t["S"] != 0
            supported[(g, n)] = t["p_two_sided"] < 0.05 and agree
            un = r.get("sample_test_no_batch_strata", {}).get("p_two_sided")
            L.append(f"| {g} | {n} | {t['samples']} | {f(t['tau'])} | {t['p_two_sided']:.4f} | {adj[n]:.4f} | {'yes' if agree else 'no'} | "
                     f"{'yes' if supported[(g, n)] else 'no'} | {'n/a' if un is None else f'{un:.4f}'} | "
                     f"{r['sample_test_linear']['p_two_sided']:.4f} | {r['sample_test_joint_boosted']['p_two_sided']:.4f} |")
    pred["S6"] = (all(supported[("GSE106474", n)] for n in ("CytoTRACE", "SR", "ORIGINS"))
                  and not any(supported[("GSE106474", n)] for n in ("NCG", "dpath", "StemFinder")),
                  "supported on GSE106474: " + (", ".join(n for n in AUDITED if supported.get(("GSE106474", n))) or "none"))

    # ---- C
    L += ["", "## C. Depth and the shared window", "", "Spearman correlation with stage, early to late.", "",
          "| series | library size | gene count | gene count given library size |", "|---|---|---|---|"]
    for g in SERIES:
        if g in d:
            dp = d[g]["depth"]
            L.append(f"| {g} | {f(dp['spearman_library_size_with_stage'])} | {f(dp['spearman_detected_genes_with_stage'])} | "
                     f"{f(dp['spearman_detected_genes_with_stage_given_library_size'])} |")
    L += ["", "| series | cells | depth | cells kept | gene count | gene-count signature | CytoTRACE |", "|---|---|---|---|---|---|---|"]
    sign = {}
    for g in SERIES:
        if g not in d:
            continue
        dp, rows = d[g]["depth"], d[g]["rows"]
        L.append(f"| {g} | all hours | raw | {d[g]['n']:,} | {f(dp['spearman_detected_genes_with_stage'])} | "
                 f"{f(rows['GCS']['spearman_with_stage'])} | {f(rows['CytoTRACE']['spearman_with_stage'])} |")
        sign[(g, "all", "raw")] = rows["CytoTRACE"]["spearman_with_stage"]
        for depth in ("1000", "500", "2000"):
            t = dp["thinned"].get(depth)
            if t:
                L.append(f"| {g} | all hours | {int(depth):,} counts | {t['cells_kept']:,} | {f(t['spearman_detected_genes_with_stage'])} | "
                         f"{f(t.get('spearman_gene_count_signature_with_stage'))} | {f(t.get('spearman_cytotrace_with_stage'))} |")
                if depth == "1000":
                    sign[(g, "all", "thin")] = t.get("spearman_cytotrace_with_stage")
                    sign[(g, "genes", "thin")] = t["spearman_detected_genes_with_stage"]
                    k = dp.get("kept_cells_raw_depth")
                    if k:
                        sign[(g, "kept", "raw")] = k["spearman_cytotrace_with_stage"]
                        L.append(f"| {g} | all hours, cells with 1,000 counts | raw | {k['cells']:,} | {f(k['spearman_detected_genes_with_stage'])} | "
                                 f"{f(k['spearman_gene_count_signature_with_stage'])} | {f(k['spearman_cytotrace_with_stage'])} |")
        for tag, label, key in (("window", "raw", "raw"), ("window_thinned", "1,000 counts", "thin")):
            w = dp.get("shared_window", {}).get(tag)
            if w:
                L.append(f"| {g} | 4 to 12 hours | {label} | {w['cells']:,} | {f(w['spearman_detected_genes_with_stage'])} | "
                         f"{f(w['spearman_gene_count_signature_with_stage'])} | {f(w['spearman_cytotrace_with_stage'])} |")
                sign[(g, "window", key)] = w["spearman_cytotrace_with_stage"]
    a, b = "GSE106474", "GSE112294"
    same = lambda x, y: x is not None and y is not None and abs(x) >= 0.1 and abs(y) >= 0.1 and x * y > 0     # noqa: E731
    opposite = lambda x, y: x is not None and y is not None and abs(x) >= 0.1 and abs(y) >= 0.1 and x * y < 0  # noqa: E731
    if (a, "all", "thin") in sign and (b, "all", "thin") in sign:
        genes_fall = sign[(a, "genes", "thin")] <= -0.1 and sign[(b, "genes", "thin")] <= -0.1
        pred["S7"] = (genes_fall and same(sign[(a, "all", "thin")], sign[(b, "all", "thin")]),
                      f"gene count at 1,000 counts: {f(sign[(a, 'genes', 'thin')])} and {f(sign[(b, 'genes', 'thin')])}; "
                      f"CytoTRACE at 1,000 counts: {f(sign[(a, 'all', 'thin')])} and {f(sign[(b, 'all', 'thin')])}")
    if (a, "window", "raw") in sign and (b, "window", "raw") in sign:
        pred["S8"] = (opposite(sign[(a, "window", "raw")], sign[(b, "window", "raw")]),
                      f"CytoTRACE on the shared window, raw depth: {f(sign[(a, 'window', 'raw')])} and {f(sign[(b, 'window', 'raw')])}")
        depth_ok = same(sign.get((a, "all", "thin")), sign.get((b, "all", "thin")))
        window_ok = same(sign[(a, "window", "raw")], sign[(b, "window", "raw")])
        both_ok = same(sign.get((a, "window", "thin")), sign.get((b, "window", "thin")))
        kept_ok = same(sign.get((a, "kept", "raw")), sign.get((b, "kept", "raw")))
        L += ["", "Reading registered in the plan (a direction counts when the absolute Spearman correlation is at least 0.1 on both series):",
              f"- equal depth, all hours: the two series {'agree' if depth_ok else 'do not agree'} in CytoTRACE's direction;",
              f"- the same cells at raw depth: they {'agree' if kept_ok else 'do not agree'};",
              f"- shared window, raw depth: they {'agree' if window_ok else 'do not agree'};",
              f"- shared window at equal depth: they {'agree' if both_ok else 'do not agree'}."]
    L += ["", "Median library size and detected genes per stage:", ""]
    for g in SERIES:
        if g in d:
            ps = d[g]["depth"]["per_stage"]
            L.append(f"- {g}: " + "; ".join(f"{k}: {v['median_library_size']:,.0f} / {v['median_detected_genes']:,.0f}" for k, v in ps.items()))

    # ---- D
    L += ["", "## D. Stratified concordance", "",
          "Kendall's tau over pairs of cells in the same stratum of the declared primitive and from different stages, on the aligned score; "
          "null from permuting the score within strata and aligning each draw again. z is descriptive: the decision is the 97.5th percentile.", "",
          "| series | row | value | null mean | null 97.5th | z | above |", "|---|---|---|---|---|---|---|"]
    conc = {}
    for g in SERIES:
        if g in d:
            for n, r in d[g]["rows"].items():
                c = r["concordance"]
                conc[(g, n)] = c["clears"]
                L.append(f"| {g} | {n} | {f(c['value'])} | {f(c['null_mean'], 4)} | {f(c['null_p975'], 4)} | {c['z']:.1f} | {'yes' if c['clears'] else 'no'} |")
    pred["S9"] = (all(conc[("GSE106474", n)] for n in CLEARING) and not any(conc[("GSE106474", n)] for n in ("CCAT", "SLICE", "MCE")),
                  "above on GSE106474: " + ", ".join(n for n in AUDITED if conc[("GSE106474", n)]))

    # ---- predictions
    L += ["", "## The registered predictions", "", "| prediction | outcome | what was observed |", "|---|---|---|"]
    for k in sorted(pred):
        L.append(f"| {k} | {'held' if pred[k][0] else 'failed'} | {pred[k][1]} |")
    return "\n".join(L) + "\n", pred


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", default=str(HERE / "results"))
    a = ap.parse_args()
    d = {g: json.loads((Path(a.dir) / f"specificity_{g}.json").read_text()) for g in SERIES
         if (Path(a.dir) / f"specificity_{g}.json").is_file()}
    text, pred = build(d)
    extra = []
    for name, title in (("depth_2", "Second plan (PREREG_depth_2.md)"), ("depth_3", "Third plan (PREREG_depth_3.md)")):
        f = Path(a.dir) / f"{name}.json"
        if f.is_file():
            pj = json.loads(f.read_text())["predictions"]
            extra += ["", f"## {title}: predictions", "", "| prediction | outcome | observed |", "|---|---|---|"]
            extra += [f"| {k} | {'held' if v['held'] else 'failed'} | {json.dumps(v['observed'])} |" for k, v in sorted(pj.items())]
            pred.update({k: (v["held"], json.dumps(v["observed"])) for k, v in pj.items()})
    f = Path(a.dir) / "calibration_cluster.json"
    if f.is_file():
        extra += ["", "## Calibration of the sample test (share of replicates called skilled)", "",
                  "| shape | rho | sample sd | batch sd | trend | registered floor | permutation floor | sample test | no batch strata | least squares |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        extra += [f"| {r['shape']} | {r['rho']} | {r['sample_sd']} | {r['batch_sd']} | {r['planted_trend']} | {pct(r['clears_registered_floor'])} | "
                  f"{pct(r['clears_permutation_floor'])} | {pct(r['sample_test_stratum_mean'])} | "
                  f"{pct(r['sample_test_stratum_mean_no_batch_strata'])} | {pct(r['sample_test_least_squares'])} |"
                  for r in json.loads(f.read_text())["rows"]]
    f = Path(a.dir) / "calibration_concordance.json"
    if f.is_file():
        extra += ["", "## Calibration of the stratified concordance (false clears, nominal 2.5%)", "", "| case | n | rho | reps | false clear |", "|---|---|---|---|---|"]
        extra += [f"| {r['case']} | {r['n']} | {r['rho']} | {r['reps']} | {pct(r['false_clear'])} |" for r in json.loads(f.read_text())["rows"]]
    text += "\n".join(extra) + "\n"
    (Path(a.dir) / "REPORT.md").write_text(text)
    (Path(a.dir) / "predictions.json").write_text(json.dumps({k: {"held": v[0], "observed": v[1]} for k, v in pred.items()}, indent=1))
    print(text)


if __name__ == "__main__":
    main()
